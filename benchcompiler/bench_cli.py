#!/usr/bin/env python3
"""bench -- the command line of the pipeline.

  bench formalize <spec.yaml> --model M --out <canonical.json>
      Stage 1: the task description (YAML of prose) -> the canonical specification.
  bench search-agent <spec.yaml> --canonical <canonical.json> --out agents/<task>_search --target N
      Stage 2a: the search agent's configuration, assembled from the two (no model).
  bench worker <spec.yaml> --canonical <canonical.json> --out agents/<task>_worker --model M
      Stage 2b: the construction worker's contract and stage plan, generated by a model.
  bench construct --config agents/<task>_search/agent.yaml --out <run dir>
      Stage 3: one search attempt (scripts/search_epoch.sh runs several).
  bench stock-freeze <run dirs> --out stock/<task> --agent agents/<task>_search
      Stage 3: the attempts' candidates, deduplicated on the identity, frozen.
  bench handover <stock/<task>/candidates.jsonl> --worker agents/<task>_worker --workers K --target T --out <dir> [--launch]
      Stage 4: the candidates split between K construction workers, each a `bench construct`.
  bench construct-resume <run dir>
      continue an interrupted run from its saved state.
  bench lessons <run dirs> --agent <agent dir> --model M
      optional: a model reads finished records and writes lessons.md into the agent dir.
  bench recipes-summary <worker run dirs>
      what a worker delivered and dropped.

Packaging (stage 5) is scripts/package.py; it needs no model.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from agentcore.config.loader import deep_merge
from agentcore.run.single import run_single
from benchcompiler.formalizer import formalize
from benchcompiler.ledger import append_ledger, format_table, load_ledger, scan_root
from benchcompiler.spec import load_raw_spec

# Every finished run appends one row here; BENCH_LEDGER moves it.
DEFAULT_LEDGER_PATH = os.environ.get("BENCH_LEDGER") or os.path.join(ROOT, "runs", "ledger.jsonl")


def map_credential_aliases(environ=os.environ) -> str:
    """Resolve the project's GitHub credential to the name the harness serves.

    Everything downstream -- the sandbox passthrough whitelist, /root/.tokens.env, the
    agent teaching -- speaks GITHUB_TOKEN; the .env file stores it as GH_FINEGRAINED_TOKEN.
    Resolved here, at the one door every command enters through, so the mapping does not
    depend on the launching shell.
    """
    if not environ.get("GITHUB_TOKEN") and environ.get("GH_FINEGRAINED_TOKEN"):
        environ["GITHUB_TOKEN"] = environ["GH_FINEGRAINED_TOKEN"]
        return "GITHUB_TOKEN taken from GH_FINEGRAINED_TOKEN"
    if not environ.get("GITHUB_TOKEN"):
        return (
            "WARNING: no GITHUB_TOKEN (and no GH_FINEGRAINED_TOKEN to take it "
            "from) -- GitHub API calls will run unauthenticated at 10 searches/min"
        )
    return ""


def cmd_formalize(args):
    """Stage 1 -- the REQUIRED first step for any new task. Raw spec in, canonical spec
    (ACCEPT) or typed diagnostics (REJECT) out. `bench search-agent` and `bench worker`
    both read its output; there is no supported path that skips it."""
    from agentcore.observability.stage_log import StageLog
    from benchcompiler import llm

    if getattr(args, "log_dir", None):
        os.environ[llm.LOG_DIR_ENV] = args.log_dir
    raw = load_raw_spec(args.spec)
    # The exchanges and the verdicts go beside the output (or the spec): formalizer.jsonl.
    log_dir = os.path.dirname(os.path.abspath(args.out or args.spec))
    with StageLog(log_dir, "formalizer"):
        result = formalize(
            raw,
            args.model or os.environ.get("AGENT_MODEL") or sys.exit("formalize needs --model (or AGENT_MODEL)"),
            judge=not args.no_judge,
            judge_model=args.judge_model,
        )
    if result.outcome == "REJECT":
        print("REJECTED:")
        for d in result.diagnostics:
            print(f"  {d}")
        if args.json:
            print(json.dumps({"outcome": "REJECT", "diagnostics": [d.__dict__ for d in result.diagnostics]}, indent=2))
        sys.exit(1)
    payload = {"outcome": result.outcome, "canonical_spec": result.canonical_spec.to_dict()}
    if args.json:
        print(json.dumps(payload, indent=2))
    else:
        print(f"ACCEPTED. spec_id={result.canonical_spec.spec_id}")
        print(f"oracle_strategy: {result.canonical_spec.oracle_strategy}")
        print(f"candidate_definition: {result.canonical_spec.candidate_definition}")
        if result.canonical_spec.assumptions:
            print(f"assumptions recorded: {len(result.canonical_spec.assumptions)}")
    if args.out:
        with open(args.out, "w") as f:
            json.dump(payload, f, indent=2)
        print(f"\nWritten to {args.out} -- next: bench search-agent and bench worker.")


def cmd_search_agent(args):
    """The SEARCH step's agent, from the spec and its canonical. Nothing is drawn."""
    from benchcompiler import search

    out = search.emit_search_agent(
        args.spec,
        args.canonical,
        args.out,
        target=args.target,
        model=args.model or os.environ.get("AGENT_MODEL") or sys.exit("search-agent needs --model (or AGENT_MODEL)"),
        name=args.name,
        known_from=args.known_from,
        budget_usd=args.cost_limit,
        wallclock_s=args.wallclock_limit,
        image=args.image or search.DEFAULT_IMAGE,
    )
    print(json.dumps(out, indent=1))


def cmd_stock_freeze(args):
    from benchcompiler import search

    m = search.freeze_stock(args.runs, args.out, agent_dir=args.agent)
    print(json.dumps({k: v for k, v in m.items() if k != "origin"}, indent=1))


def cmd_worker(args):
    from benchcompiler import llm, worker

    if getattr(args, "log_dir", None):
        os.environ[llm.LOG_DIR_ENV] = args.log_dir
    out = worker.emit_worker(
        args.spec,
        args.canonical,
        args.out,
        model=args.model,
        sample_size=args.sample_size,
        name=args.name,
        rounds=args.rounds,
        contract_json=args.contract_json,
    )
    print(json.dumps(out, indent=1))


def cmd_handover(args):
    from benchcompiler import search

    exclude = []
    if getattr(args, "exclude", None):
        exclude += search.read_exclusions(args.exclude)
    if getattr(args, "exclude_finished", None):
        fin = search.finished_candidates(args.exclude_finished, args.worker)
        print(
            f"finished in {', '.join(args.exclude_finished)}: {len(fin['delivered'])} delivered, "
            f"{len(fin['dropped'])} dropped"
        )
        exclude += fin["delivered"] + fin["dropped"]
    m = search.handover(
        args.stock,
        args.worker,
        args.out,
        workers=args.workers,
        target=args.target,
        launch=args.launch,
        sample=args.sample,
        seed=args.seed,
        exclude=exclude or None,
        shuffle=getattr(args, "shuffle", False),
        size_order=getattr(args, "size_order", None),
    )
    print(json.dumps(m, indent=1))


def _ns(args, **overrides):
    """A shallow copy of an argparse Namespace with some fields replaced.

    `construct-resume` derives its output dir from the run being resumed rather than from a
    required --out, so the shared post-processing needs a namespace whose `out` points at the
    right place without mutating the caller's."""
    return argparse.Namespace(**{**vars(args), **overrides})


def _load_overrides(path: str | None) -> dict | None:
    """Config overlay applied on top of agent.yaml at load time.

    Needed to run a controlled A/B from ONE agent config: the control arm is the same commit,
    model, budget and task, differing only in the design under test. Editing agent.yaml between
    arms instead would make the two runs incomparable and unreproducible.
    """
    if not path:
        return None
    import yaml

    with open(path) as f:
        return yaml.safe_load(f) or {}


def _default_instance_for(config_path: str) -> str | None:
    """An agent's own instances.jsonl, next to its agent.yaml.

    Without it, omitting --instance would validate the task against an empty dict. An agent
    that ships a spec should not need to be told where it is.
    """
    d = os.path.dirname(os.path.abspath(config_path))
    cand = os.path.join(d, "instances", "instances.jsonl")
    return cand if os.path.exists(cand) else None


def cmd_construct(args):
    inst = args.instance or _default_instance_for(args.config)
    if inst and not args.instance:
        print(f"(--instance not given; using the agent's own {inst})")
    overrides = _load_overrides(getattr(args, "overrides", None)) or {}
    # CLI overrides sit above the env layer in the loader's merge, which is what typing
    # the flag means.
    if getattr(args, "model", None):
        overrides = deep_merge(overrides, {"models": {"main": {"name": args.model}}})
    result = run_single(
        args.config, instance=inst, output_dir=args.out, workspace=args.workspace, overrides=overrides or None
    )
    _post_construct(args, result, out_dir=args.out)


def cmd_construct_resume(args):
    """Continue an interrupted construct run, then judge/ledger it exactly like a fresh one.

    Every construct run snapshots its full state after each cycle (observability.state), so a
    run killed by a provider outage, a container crash, or a machine reboot does not have to
    start over -- its working_set, action_log, stage position and spent budget are all
    restorable. Four real runs died with 73-86% of their cost budget unspent and 7-13 already
    validated instances in hand; without this entry point that work could only be recovered by
    dropping to the lower-level `agent resume` CLI, which does not run the judge or append to
    the ledger, so the result never became part of the study.

    Per-instance sandboxes rebuild themselves from their recorded recipes on first use after a
    resume (agentcore.tools.containers), so a resumed run does not silently continue in an
    environment missing the toolchain it installed before the interruption.
    """
    from agentcore.run.resume import resume_run

    # --model rides the CLI-override layer like a fresh construct; --instance is refused
    # outright -- a resumed run's instance IS its identity (run_meta.json), and swapping it
    # mid-run is the fork operation, not a resume.
    if getattr(args, "instance", None):
        raise SystemExit(
            "construct-resume cannot take --instance: the resumed run keeps the instance "
            "it was launched with (run_meta.json). To continue this state against a NEW "
            "task, use the fork path (agent resume --task ...) or start a fresh construct."
        )
    overrides = {"models": {"main": {"name": args.model}}} if getattr(args, "model", None) else None
    result = resume_run(args.run_dir, output_dir=args.out or None, overrides=overrides)
    # continue-in-place (no --out) keeps writing into the original run dir
    out_dir = args.out or args.run_dir
    print(f"(resumed from {args.run_dir})")
    _post_construct(args, result, out_dir=out_dir)


def _post_construct(args, result, *, out_dir):
    """Record a finished construct run in the ledger. Shared by `construct` and
    `construct-resume` so a resumed run is treated exactly like an uninterrupted one.

    No LLM judge grades the run here. Correctness is established by facts instead: per-state
    validators that re-execute against real clones and containers, the declared negative
    control (WorklistStateSpec.discriminates), and `bench certify`, which re-runs every
    instance from its committed snapshot.
    """
    print(
        json.dumps(
            {"success": result.success, "reason": result.reason, "steps": result.steps, "cost": result.cost}, indent=2
        )
    )

    args = _ns(args, out=out_dir)
    ws = result.working_set or {}
    ledger_path = getattr(args, "ledger", None) or DEFAULT_LEDGER_PATH
    sample = ws.get("final_sample")
    if "final_sample" not in ws:
        print(
            "\nNo final_sample recorded -- the run ended before wrap_up, or the agent did "
            "not follow the recording convention."
        )
    else:
        print(f"\nDelivered: {len(sample) if isinstance(sample, list) else 0} item(s) published to final_sample.")
    append_ledger(scan_root(args.out), ledger_path)


def cmd_lessons(args):
    from benchcompiler import lessons, llm

    if args.log_dir:
        os.environ[llm.LOG_DIR_ENV] = args.log_dir
    kw = {"chunk_chars": args.chunk_chars} if args.chunk_chars else {}
    if args.max_lessons:
        kw["max_lessons"] = args.max_lessons
    m = lessons.write_lessons(
        args.runs,
        agent_dir=args.agent,
        model=args.model,
        out_path=args.out,
        remerge=args.remerge,
        seed_from=args.seed_from,
        **kw,
    )
    print(json.dumps(m, indent=1))


def cmd_recipes_merge(args):
    """Phase 4 of the recipes plan: pool the accepted recipe instances of finished runs."""
    from benchcompiler import recipes_pool

    m = recipes_pool.merge(args.runs, args.out, args.contract, name=args.name)
    print(json.dumps({k: v for k, v in m.items() if k != "verbs"}, indent=1))
    if args.certify:
        print(json.dumps(recipes_pool.certify(args.out, log=lambda s: print(s, file=sys.stderr)), indent=1))


def cmd_recipes_certify(args):
    from benchcompiler import recipes_pool

    print(
        json.dumps(
            recipes_pool.certify(args.artifact_dir, limit=args.limit, log=lambda s: print(s, file=sys.stderr)), indent=1
        )
    )


def cmd_recipes_summary(args):
    from benchcompiler import recipes_pool

    for run in args.runs:
        print(recipes_pool.summary_text(recipes_pool.summary(run)))


def cmd_ledger_scan(args):
    """Scan one or more run-output roots (construct-parallel dirs, ad hoc flow-attempt
    dirs, or single run_single dirs) and append a normalized row per attempt to the
    persistent ledger -- see ledger.py for why this exists (no prior version control or
    cross-run record existed for this project's ~20+ construction-agent iterations)."""
    all_rows = []
    for root in args.roots:
        rows = scan_root(root, task=args.task)
        all_rows.extend(rows)
        print(f"{root}: {len(rows)} attempt(s) found")
    append_ledger(all_rows, args.ledger)
    print(f"\nAppended {len(all_rows)} row(s) to {args.ledger}")


def cmd_ledger_show(args):
    rows = load_ledger(args.ledger)
    if args.task:
        rows = [r for r in rows if r.get("task") == args.task]
    if not rows:
        print(f"No ledger rows found in {args.ledger}" + (f" for task={args.task}" if args.task else ""))
        return
    print(format_table(rows))


def build_parser():
    ap = argparse.ArgumentParser(prog="bench", description="BenchMeUp: from a task description to a benchmark.")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("formalize", help="stage 1 -- REQUIRED first step: raw spec -> canonical spec or REJECT")
    p.add_argument("spec", help="path to a raw BenchSpec YAML")
    p.add_argument("--model", default=None)
    p.add_argument(
        "--judge-model", default=None, help="the model that reviews the generated search rules (default: --model)"
    )
    p.add_argument(
        "--no-judge", action="store_true", help="skip the review of the generated search rules by a second model call"
    )
    p.add_argument("--json", action="store_true", help="print the full JSON payload, not a human summary")
    p.add_argument("--out", default=None, help="write the {outcome, canonical_spec} JSON here too")
    p.add_argument(
        "--log-dir", default=None, help="write every round's prompt and answer here as plain files, for review"
    )
    p.set_defaults(func=cmd_formalize)

    p = sub.add_parser(
        "search-agent",
        help="emit the searching agent (finds candidates at scale) from the "
        "spec and its canonical; nothing is drawn by a model",
    )
    p.add_argument("spec", help="the NL spec (yaml)")
    p.add_argument("--canonical", required=True, help="the canonical json (bench formalize output)")
    p.add_argument("--out", required=True, help="the agent directory to write (agents/<name>_search)")
    p.add_argument("--target", type=int, required=True, help="how many candidates one run must find")
    p.add_argument("--model", default=None, help="the agent's model (or AGENT_MODEL)")
    p.add_argument("--name", default=None)
    p.add_argument(
        "--known-from", nargs="*", default=[], help="stock files or run dirs whose candidates do not count again"
    )
    p.add_argument("--cost-limit", type=float, default=2.0)
    p.add_argument("--wallclock-limit", type=int, default=6 * 3600)
    p.add_argument("--image", default=None, help="the agent's container image")
    p.set_defaults(func=cmd_search_agent, image=None)

    p = sub.add_parser("stock-freeze", help="merge searching runs' stocks into a frozen stock on the identity")
    p.add_argument("runs", nargs="+", help="run dirs (or their stock/candidates.jsonl)")
    p.add_argument("--out", required=True, help="artifacts/stock/<family>")
    p.add_argument("--agent", required=True, help="the searching agent dir (for the identity)")
    p.set_defaults(func=cmd_stock_freeze)

    p = sub.add_parser(
        "worker",
        help="emit a worker (instance construction through the stages) from the "
        "spec and its canonical; draws the family config and the stage "
        "sections with --model",
    )
    p.add_argument("spec", help="the NL spec (yaml)")
    p.add_argument("--canonical", required=True, help="the canonical json (bench formalize output)")
    p.add_argument("--out", required=True, help="the worker directory to write (agents/<name>_worker)")
    p.add_argument("--model", required=True, help="the model that draws the config and the stage sections")
    p.add_argument("--sample-size", type=int, default=10)
    p.add_argument("--name", default=None)
    p.add_argument("--rounds", type=int, default=6, help="draw rounds for the family config (each refusal costs one)")
    p.add_argument(
        "--contract-json",
        default=None,
        help="an accepted config kept by an earlier run (<out>/contract.accepted.json): only the stage text is drawn",
    )
    p.add_argument(
        "--log-dir", default=None, help="write every round's prompt and answer here as plain files, for review"
    )
    p.set_defaults(func=cmd_worker)

    p = sub.add_parser("handover", help="fill workers' candidate pools from a frozen stock and launch them")
    p.add_argument("stock", help="the frozen candidates.jsonl")
    p.add_argument("--worker", required=True, help="the worker agent dir (agents/<name>_worker)")
    p.add_argument("--workers", type=int, default=2)
    p.add_argument("--target", type=int, required=True, help="total instances wanted across the workers")
    p.add_argument("--out", required=True)
    p.add_argument("--launch", action="store_true")
    p.add_argument("--sample", type=int, default=0, help="hand over a random sample of this many candidates (0: all)")
    p.add_argument("--seed", type=int, default=1)
    p.add_argument(
        "--shuffle",
        action="store_true",
        help="shuffle the candidates (--seed fixes the order) and deal "
        "them one per worker in turn, instead of whole repositories",
    )
    p.add_argument(
        "--size-order",
        default=None,
        metavar="CSV",
        help="hand out the smallest repositories first: a CSV of repository (owner/name), size",
    )
    p.add_argument(
        "--exclude", default=None, help="a file of identities (f1|f2 per line, or JSON lines) that never reach a worker"
    )
    p.add_argument(
        "--exclude-finished",
        nargs="*",
        default=None,
        metavar="EPOCH_DIR",
        help="exclude what these earlier runs delivered or dropped",
    )
    p.set_defaults(func=cmd_handover)

    p = sub.add_parser(
        "construct", help="run one agent (a search attempt or a construction worker) from its agent.yaml"
    )
    p.add_argument("--config", required=True)
    p.add_argument("--instance", default=None)
    p.add_argument("--out", required=True)
    p.add_argument("--workspace", default=None)
    p.add_argument("--model", default=None)
    p.add_argument("--overrides", default=None, help="YAML config overlay applied on top of --config (for A/B arms)")
    p.add_argument("--ledger", default=None, help="append this run to a specific ledger (default: the study ledger)")
    p.set_defaults(func=cmd_construct)

    p = sub.add_parser(
        "construct-resume",
        help="continue an interrupted construct run (restores working_set, stage, "
        "budget and per-instance sandboxes), then judge + ledger it",
    )
    p.add_argument("run_dir", help="the output dir of the interrupted run")
    p.add_argument("--out", default=None, help="write the continuation to a NEW dir (default: continue in place)")
    p.add_argument("--instance", default=None)
    p.add_argument("--model", default=None)
    p.add_argument("--ledger", default=None)
    p.set_defaults(func=cmd_construct_resume)

    p = sub.add_parser(
        "lessons",
        help="a model reads the COMPLETE records of a family's agents (search "
        "attempts or workers, finished or running) and writes lessons.md "
        "into the agent dir, where every brief reads it each cycle",
    )
    p.add_argument("runs", nargs="+", help="run dirs, or epoch dirs holding worker_*/ or attempt_*/")
    p.add_argument("--agent", required=True, help="the agent dir whose brief gets the lessons")
    p.add_argument("--model", required=True, help="the model that reads the records")
    p.add_argument("--out", default=None, help="lessons.md path (default: <first epoch dir>/lessons.md)")
    p.add_argument(
        "--chunk-chars",
        type=int,
        default=None,
        help="characters of record per model call; the record is cut at cycle heads only",
    )
    p.add_argument("--log-dir", default=None, help="write every prompt and answer here (LLM_LOG_DIR)")
    p.add_argument(
        "--max-lessons",
        type=int,
        default=None,
        help="the merged list's ceiling (default 60, LESSONS_MAX); it rides every prompt every cycle",
    )
    p.add_argument(
        "--remerge",
        action="store_true",
        help="rank and fold the per-agent lists kept in lessons.json again, one call, no re-reading",
    )
    p.add_argument(
        "--seed-from",
        default=None,
        help="an earlier epoch dir (or its lessons.json): start this epoch's reader from what it "
        "learned; applies once, when this epoch has no state yet",
    )
    p.set_defaults(func=cmd_lessons)

    p = sub.add_parser("recipes-merge", help="pool accepted recipe instances (directories of scripts)")
    p.add_argument("runs", nargs="+")
    p.add_argument("--out", required=True)
    p.add_argument("--contract", required=True, help="the family contract (contract.yaml)")
    p.add_argument("--name", default="benchmark")
    p.add_argument("--certify", action="store_true", help="replay every instance after merging")
    p.set_defaults(func=cmd_recipes_merge)

    p = sub.add_parser("recipes-certify", help="replay every instance of a recipe pool from its Dockerfile")
    p.add_argument("artifact_dir")
    p.add_argument("--limit", type=int, default=None)
    p.set_defaults(func=cmd_recipes_certify)

    p = sub.add_parser("recipes-summary", help="the run summary of a worker, from its record (agent_state.json)")
    p.add_argument("runs", nargs="+")
    p.set_defaults(func=cmd_recipes_summary)

    p = sub.add_parser(
        "ledger-scan", help="scan run-output root(s) and append normalized attempt rows to the persistent ledger"
    )
    p.add_argument("roots", nargs="+", help="one or more construct-parallel / flow-parallel / single run dirs")
    p.add_argument("--task", default=None, help="override the auto-detected task name (applies to all roots given)")
    p.add_argument("--ledger", default=DEFAULT_LEDGER_PATH)
    p.set_defaults(func=cmd_ledger_scan)

    p = sub.add_parser("ledger-show", help="print the persistent ledger as a sorted table")
    p.add_argument("--ledger", default=DEFAULT_LEDGER_PATH)
    p.add_argument("--task", default=None, help="filter to one task")
    p.set_defaults(func=cmd_ledger_show)

    return ap


def main():
    note = map_credential_aliases()
    if note:
        print(note, file=sys.stderr)
    args = build_parser().parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
